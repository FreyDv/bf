// Seals the production environment files of an application with `kubeseal` and writes the result under
// deploy/ (ADR-020, ADR-060). It never talks to the cluster: the public certificate is committed in
// deploy/sealed-secrets/pub-cert.pem, and every value is sealed for exactly one secret name and namespace
// (strict scope), so a stolen ciphertext cannot be replayed under another name.
//
//   node ../../scripts/seal-secret.ts          run from apps/<app>: every apps/<app>/.env[.<name>].production
//                                              becomes deploy/apps/<app>/secrets.yaml
//   node scripts/seal-secret.ts --env <file> --name <secret> --namespace <ns> --out <path>
//                                              one SealedSecret manifest, for charts that are not `app`
//   node scripts/seal-secret.ts --check        every encryptedData value in deploy/apps/*/secrets.yaml is ciphertext
//
// A value is read only from the env file and goes to kubeseal through stdin: never into argv, a log, an error
// message or a temporary file. Messages name the key and the line, never the value.
import { spawnSync } from 'node:child_process';
import { X509Certificate } from 'node:crypto';
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { basename, dirname, relative, resolve } from 'node:path';
import { parseEnv } from 'node:util';

// One environment, one namespace (ADR-038 item 1).
export const NAMESPACE = 'bf';
// The chart names a release `Release.Name | trunc 40 | trimSuffix "-"` (deploy/charts/app/templates/_helpers.tpl).
// A longer name would be truncated there but not here, and a strict-scope secret would not decrypt.
export const MAX_RELEASE_NAME = 40;
export const CERT_PATH = 'deploy/sealed-secrets/pub-cert.pem';

const KEY_PATTERN = /^[A-Z_][A-Z0-9_]*$/;
const EXTRA_FILE = /^\.env\.(.+)\.production$/;
const EXTRA_NAME = /^[a-z][a-z0-9-]*$/;
const DNS_LABEL = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?$/;
// kubeseal output is a 2-byte length of the RSA-wrapped session key (512 bytes for 4096 bits, 256 for 2048)
// followed by the wrapped key and the AES-GCM payload, in base64: long, and starting "Ag" or "AQ".
const CIPHERTEXT = /^A[gQ][A-Za-z0-9+/]{298,}={0,2}$/;

const HEADER =
  '# Generated by `pnpm secrets:seal` (scripts/seal-secret.ts, ADR-020, ADR-060). Sealed values only; do not edit.';

export class SealError extends Error {}

export interface SealRequest {
  name: string;
  namespace: string;
  cert: string;
}

// The only part that touches kubeseal, so tests can stand a fake in its place.
export interface Sealer {
  available(): boolean;
  seal(value: string, request: SealRequest): string;
}

export function kubesealArgs({ name, namespace, cert }: SealRequest): string[] {
  return ['--raw', '--cert', cert, '--scope', 'strict', '--name', name, '--namespace', namespace];
}

export const kubesealSealer: Sealer = {
  available() {
    return spawnSync('kubeseal', ['--version'], { stdio: 'ignore' }).status === 0;
  },
  seal(value, request) {
    const result = spawnSync('kubeseal', kubesealArgs(request), {
      input: value,
      encoding: 'utf8',
      maxBuffer: 1 << 20,
    });
    // kubeseal's own stderr is not forwarded: the message names the key (the caller) and nothing else.
    if (result.error) throw new SealError(`kubeseal could not run (${result.error.message})`);
    if (result.status !== 0) throw new SealError(`kubeseal exited with status ${result.status}`);
    return result.stdout.trim();
  },
};

export interface Context {
  cwd: string;
  root: string;
  sealer: Sealer;
  now: Date;
  out: (line: string) => void;
  err: (line: string) => void;
}

export interface EnvEntry {
  key: string;
  value: string;
}

// Checks the raw lines first, because `util.parseEnv` is lenient where a secret must not be: it keeps the last of
// duplicate keys, cuts an unquoted value at `#`, accepts any key, and silently skips a line it cannot read. Then
// parseEnv produces the values, and each one must equal what the line literally says. Returns the entries in file
// order, or every problem found (line and key only, never a value).
export function parseEnvStrict(source: string): { entries: EnvEntry[]; errors: string[] } {
  const errors: string[] = [];
  const expected = new Map<string, string>();
  const lines = source.replace(/^﻿/, '').split(/\r?\n/);
  const open = new Set<string>();
  lines.forEach((line, index) => {
    const at = `line ${index + 1}`;
    const text = line.trim();
    if (text === '' || text.startsWith('#')) return;
    const eq = text.indexOf('=');
    if (eq < 0) {
      errors.push(`${at}: not KEY=value`);
      return;
    }
    const key = text.slice(0, eq).trim();
    if (!KEY_PATTERN.test(key)) {
      errors.push(`${at}: key must match ${KEY_PATTERN.source}`);
      return;
    }
    if (open.has(key)) {
      errors.push(`${at}: duplicate key ${key}`);
      return;
    }
    open.add(key);
    const raw = text.slice(eq + 1).trim();
    if (raw === '') {
      errors.push(`${at}: empty value for ${key}`);
      return;
    }
    const quote = raw[0];
    if (quote === '"' || quote === "'" || quote === '`') {
      if (raw.length < 2 || !raw.endsWith(quote)) {
        errors.push(`${at}: ${key} is a multiline value or has text after its closing quote`);
        return;
      }
      const inner = raw.slice(1, -1);
      if (inner === '') errors.push(`${at}: empty value for ${key}`);
      else if (inner.includes(quote)) errors.push(`${at}: ${key} has a quote inside its quotes`);
      else expected.set(key, inner);
      return;
    }
    if (raw.includes('#')) {
      errors.push(`${at}: unquoted # in the value of ${key}; quote the value`);
      return;
    }
    expected.set(key, raw);
  });
  if (errors.length > 0) return { entries: [], errors };

  const parsed = parseEnv(source);
  const entries: EnvEntry[] = [];
  for (const [key, literal] of expected) {
    const value = parsed[key];
    if (value === undefined) {
      errors.push(`${key}: not read by the parser`);
    } else if (/[\r\n]/.test(value)) {
      errors.push(`${key}: multiline value (a \\n escape counts)`);
    } else if (value !== literal) {
      errors.push(`${key}: the parser reads it differently from the file`);
    } else {
      entries.push({ key, value });
    }
  }
  if (errors.length === 0 && entries.length === 0) errors.push('no keys');
  return { entries, errors };
}

// ---- secrets.yaml: written in one fixed shape, read back in the same shape (no YAML dependency) ----

export interface SealedSet {
  // Secret name -> sealed values in file order.
  main: { name: string; data: [string, string][] };
  extras: { part: string; name: string; data: [string, string][] }[];
}

export function renderSecretsYaml(set: SealedSet): string {
  const lines = [HEADER, 'secret:', '  encryptedData:'];
  for (const [key, cipher] of set.main.data) lines.push(`    ${key}: ${cipher}`);
  if (set.extras.length > 0) lines.push('extraSecrets:');
  for (const extra of set.extras) {
    lines.push(`  ${extra.part}:`, '    encryptedData:');
    for (const [key, cipher] of extra.data) lines.push(`      ${key}: ${cipher}`);
  }
  return `${lines.join('\n')}\n`;
}

export function renderManifest(name: string, namespace: string, data: [string, string][]): string {
  const lines = [
    HEADER,
    'apiVersion: bitnami.com/v1alpha1',
    'kind: SealedSecret',
    'metadata:',
    `  name: ${name}`,
    `  namespace: ${namespace}`,
    'spec:',
    '  encryptedData:',
    ...data.map(([key, cipher]) => `    ${key}: ${cipher}`),
    '  template:',
    '    metadata:',
    `      name: ${name}`,
    `      namespace: ${namespace}`,
    '    type: Opaque',
  ];
  return `${lines.join('\n')}\n`;
}

// Strict reader of what renderSecretsYaml writes. Returns every problem as `file:line: message`; the value of a
// bad line is never repeated, since a failing check usually means a plaintext value.
export function checkSecretsYaml(source: string, file: string): string[] {
  const errors: string[] = [];
  const fail = (index: number, message: string) => errors.push(`${file}:${index + 1}: ${message}`);
  type Where = 'top' | 'main' | 'mainData' | 'extras' | 'extra' | 'extraData';
  let where: Where = 'top';
  let seenMain = false;
  let keys = 0;
  const seenKeys = new Set<string>();
  const closeData = (index: number) => {
    if (where === 'mainData' || where === 'extraData') {
      if (keys === 0) fail(index, 'encryptedData has no keys');
    }
    keys = 0;
    seenKeys.clear();
  };
  const lines = source.split('\n');
  if (lines.at(-1) === '') lines.pop();
  lines.forEach((line, index) => {
    if (line.startsWith('#') || line === '') return;
    let match: RegExpExecArray | null;
    if (line === 'secret:') {
      closeData(index);
      if (seenMain) fail(index, 'duplicate `secret:`');
      seenMain = true;
      where = 'main';
    } else if (line === 'extraSecrets:') {
      closeData(index);
      where = 'extras';
    } else if (line === '  encryptedData:' && where === 'main') {
      where = 'mainData';
    } else if (
      (match = /^ {2}([a-z][a-z0-9-]*):$/.exec(line)) &&
      ['extras', 'extraData'].includes(where)
    ) {
      closeData(index);
      where = 'extra';
    } else if (line === '    encryptedData:' && where === 'extra') {
      where = 'extraData';
    } else if (
      (match = /^( {4}| {6})([A-Z_][A-Z0-9_]*): (\S+)$/.exec(line)) &&
      ((match[1]!.length === 4 && where === 'mainData') ||
        (match[1]!.length === 6 && where === 'extraData'))
    ) {
      keys += 1;
      if (seenKeys.has(match[2]!)) fail(index, `duplicate key ${match[2]}`);
      seenKeys.add(match[2]!);
      if (!CIPHERTEXT.test(match[3]!)) fail(index, `${match[2]} is not kubeseal ciphertext`);
    } else {
      fail(index, 'not the shape `pnpm secrets:seal` writes');
    }
  });
  closeData(lines.length);
  if (!seenMain) errors.push(`${file}: no \`secret:\` block`);
  return errors;
}

export function checkAll(root: string): { errors: string[]; files: number } {
  const apps = resolve(root, 'deploy/apps');
  const errors: string[] = [];
  let files = 0;
  if (existsSync(apps)) {
    for (const app of readdirSync(apps).sort()) {
      const file = resolve(apps, app, 'secrets.yaml');
      if (!existsSync(file)) continue;
      files += 1;
      errors.push(...checkSecretsYaml(readFileSync(file, 'utf8'), relative(root, file)));
    }
  }
  return { errors, files };
}

// ---- sources and preflight ----

// The env file must never be committable: `git check-ignore` says so for the file as git sees it (not tracked, not
// outside the repository, matched by an ignore rule).
function requireIgnored(root: string, file: string): void {
  const result = spawnSync('git', ['check-ignore', '-q', '--', file], { cwd: root });
  if (result.status !== 0) {
    throw new SealError(
      `${relative(root, file) || file} is not ignored by git; refusing to read secrets from a file that could be committed`,
    );
  }
}

function readEnvFile(file: string, label: string): EnvEntry[] {
  const { entries, errors } = parseEnvStrict(readFileSync(file, 'utf8'));
  if (errors.length > 0) {
    throw new SealError(`${label}:\n${errors.map((error) => `  ${error}`).join('\n')}`);
  }
  return entries;
}

function preflight(ctx: Context): string {
  if (!ctx.sealer.available()) throw new SealError('kubeseal is not on PATH');
  const cert = resolve(ctx.root, CERT_PATH);
  if (!existsSync(cert)) throw new SealError(`${CERT_PATH} does not exist`);
  let parsed: X509Certificate;
  try {
    parsed = new X509Certificate(readFileSync(cert));
  } catch {
    throw new SealError(`${CERT_PATH} is not a certificate`);
  }
  if (new Date(parsed.validFrom) > ctx.now) throw new SealError(`${CERT_PATH} is not valid yet`);
  if (new Date(parsed.validTo) <= ctx.now) throw new SealError(`${CERT_PATH} has expired`);
  return cert;
}

function sealEntries(
  ctx: Context,
  cert: string,
  entries: EnvEntry[],
  name: string,
  namespace: string,
) {
  return entries.map(({ key, value }): [string, string] => {
    let cipher: string;
    try {
      cipher = ctx.sealer.seal(value, { name, namespace, cert });
    } catch (error) {
      throw new SealError(`sealing ${key} for ${name} failed: ${(error as Error).message}`);
    }
    if (!CIPHERTEXT.test(cipher)) throw new SealError(`kubeseal returned no ciphertext for ${key}`);
    return [key, cipher];
  });
}

// Temp file next to the target, renamed over it: a reader sees the old file or the new one, never half of one.
// The content is ciphertext only, so even a leftover temp file holds no plaintext.
function writeAtomic(file: string, content: string): void {
  mkdirSync(dirname(file), { recursive: true });
  const temp = `${file}.${process.pid}.tmp`;
  try {
    writeFileSync(temp, content);
    renameSync(temp, file);
  } catch (error) {
    rmSync(temp, { force: true });
    throw error;
  }
}

// ---- modes ----

function appMode(ctx: Context): void {
  const cwd = realpathSync(ctx.cwd);
  const apps = resolve(realpathSync(ctx.root), 'apps');
  if (dirname(cwd) !== apps) {
    throw new SealError(
      'run it from an application directory (apps/<app>), as the `secrets:seal` script of that app does',
    );
  }
  const app = basename(cwd);
  if (app.length > MAX_RELEASE_NAME || app.endsWith('-')) {
    throw new SealError(
      `app name ${app} cannot be a Helm release name: the chart cuts it to ${MAX_RELEASE_NAME} characters and trims a trailing "-" (deploy/charts/app/templates/_helpers.tpl), so strict-scope secrets would not decrypt; rename the directory`,
    );
  }

  const mainFile = resolve(cwd, '.env.production');
  if (!existsSync(mainFile)) {
    throw new SealError(
      `apps/${app}/.env.production does not exist; an app with a secrets:seal script must have one`,
    );
  }
  const extraFiles = readdirSync(cwd)
    .map((file) => ({ file, match: EXTRA_FILE.exec(file) }))
    .filter((item): item is { file: string; match: RegExpExecArray } => item.match !== null)
    .map(({ file, match }) => ({ file, part: match[1]! }))
    .sort((a, b) => a.part.localeCompare(b.part));
  for (const { file, part } of extraFiles) {
    if (!EXTRA_NAME.test(part)) {
      throw new SealError(
        `apps/${app}/${file}: the name between ".env." and ".production" must match ${EXTRA_NAME.source}`,
      );
    }
  }

  const sources = [
    { label: `apps/${app}/.env.production`, file: mainFile, part: null as string | null },
    ...extraFiles.map(({ file, part }) => ({
      label: `apps/${app}/${file}`,
      file: resolve(cwd, file),
      part,
    })),
  ];
  for (const source of sources) requireIgnored(ctx.root, source.file);
  const parsed = sources.map((source) => ({
    ...source,
    entries: readEnvFile(source.file, source.label),
  }));

  const cert = preflight(ctx);
  const sealed: SealedSet = {
    main: {
      name: `${app}-secrets`,
      data: sealEntries(ctx, cert, parsed[0]!.entries, `${app}-secrets`, NAMESPACE),
    },
    extras: parsed.slice(1).map(({ part, entries }) => {
      const name = `${app}-${part}-secrets`;
      return { part: part!, name, data: sealEntries(ctx, cert, entries, name, NAMESPACE) };
    }),
  };

  const out = resolve(ctx.root, 'deploy/apps', app, 'secrets.yaml');
  writeAtomic(out, renderSecretsYaml(sealed));
  const names = [sealed.main, ...sealed.extras].map(
    (item) => `${item.name} (${item.data.length} keys)`,
  );
  ctx.out(`sealed ${names.join(', ')} into ${relative(ctx.root, out)}`);
}

function manifestMode(ctx: Context, flags: Map<string, string>): void {
  const env = resolve(ctx.cwd, flags.get('--env')!);
  const name = flags.get('--name')!;
  const namespace = flags.get('--namespace')!;
  const out = resolve(ctx.cwd, flags.get('--out')!);
  for (const [flag, value] of [
    ['--name', name],
    ['--namespace', namespace],
  ] as const) {
    if (!DNS_LABEL.test(value) || value.length > 63) {
      throw new SealError(`${flag} must be a Kubernetes name: lower case letters, digits and "-"`);
    }
  }
  if (!existsSync(env)) throw new SealError(`${flags.get('--env')} does not exist`);
  requireIgnored(dirname(env), env);
  const entries = readEnvFile(env, flags.get('--env')!);
  const cert = preflight(ctx);
  writeAtomic(
    out,
    renderManifest(name, namespace, sealEntries(ctx, cert, entries, name, namespace)),
  );
  ctx.out(`sealed ${name} (${entries.length} keys) into ${relative(ctx.cwd, out) || out}`);
}

function checkMode(ctx: Context): void {
  const { errors, files } = checkAll(ctx.root);
  if (errors.length > 0) {
    throw new SealError(
      `secrets.yaml is not sealed:\n${errors.map((error) => `  ${error}`).join('\n')}`,
    );
  }
  ctx.out(`seal-secret --check: OK (${files} secrets.yaml)`);
}

const USAGE = [
  'usage:',
  '  node ../../scripts/seal-secret.ts                      (from apps/<app>)',
  '  node scripts/seal-secret.ts --env <file> --name <secret> --namespace <ns> --out <path>',
  '  node scripts/seal-secret.ts --check',
].join('\n');

const FLAGS = ['--env', '--name', '--namespace', '--out'];

// Returns the exit code; every failure is a message on `err` without a value in it.
export function run(argv: string[], ctx: Context): number {
  try {
    if (argv.length === 0) {
      appMode(ctx);
    } else if (argv.length === 1 && argv[0] === '--check') {
      checkMode(ctx);
    } else {
      const flags = new Map<string, string>();
      for (let i = 0; i < argv.length; i += 2) {
        const flag = argv[i]!;
        const value = argv[i + 1];
        if (
          !FLAGS.includes(flag) ||
          value === undefined ||
          value.startsWith('--') ||
          flags.has(flag)
        ) {
          throw new SealError(USAGE);
        }
        flags.set(flag, value);
      }
      if (FLAGS.some((flag) => !flags.has(flag))) throw new SealError(USAGE);
      manifestMode(ctx, flags);
    }
    return 0;
  } catch (error) {
    if (!(error instanceof SealError)) throw error;
    ctx.err(`seal-secret: ${error.message}`);
    return 1;
  }
}

if (import.meta.main) {
  process.exitCode = run(process.argv.slice(2), {
    cwd: process.cwd(),
    root: resolve(import.meta.dirname, '..'),
    sealer: kubesealSealer,
    now: new Date(),
    out: (line) => console.log(line),
    err: (line) => console.error(line),
  });
}
