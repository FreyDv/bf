#!/usr/bin/env node
// Runs the nestjs-trpc CLI for one app and writes the router type into @bf/contracts.
//   node ../../scripts/trpc-generate.mjs <service> [extra cli args]
// The npm tarball ships the native binary without the executable bit, so we chmod it first.
import { spawnSync } from 'node:child_process';
import { chmodSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const [service, ...extra] = process.argv.slice(2);
if (!service) {
  console.error('usage: trpc-generate.mjs <service>');
  process.exit(2);
}

// `nestjs-trpc` has an `exports` map without `./package.json`; resolve the bin entry instead.
const pkgDir = resolve(process.cwd(), 'node_modules', 'nestjs-trpc');
if (!existsSync(join(pkgDir, 'bin', 'nestjs-trpc.js'))) {
  console.error(`nestjs-trpc is not installed in ${process.cwd()}`);
  process.exit(1);
}
const platform = { darwin: 'apple-darwin', linux: 'unknown-linux-gnu', win32: 'pc-windows-msvc' }[
  process.platform
];
const arch = { x64: 'x86_64', arm64: 'aarch64' }[process.arch];
const bin = join(
  pkgDir,
  'native',
  `${arch}-${platform}`,
  process.platform === 'win32' ? 'nestjs-trpc.exe' : 'nestjs-trpc',
);
if (existsSync(bin)) chmodSync(bin, 0o755);

const outDir = mkdtempSync(join(tmpdir(), `trpc-${service}-`));
// Every app keeps a literal `TRPCModule.forRoot({...})` in src/trpc.module.ts; the CLI globs
// router files relative to that file's directory, i.e. the whole src tree.
const entrypoint = resolve(process.cwd(), 'src/trpc.module.ts');
const res = spawnSync(
  process.execPath,
  [
    join(pkgDir, 'bin', 'nestjs-trpc.js'),
    'generate',
    '--entrypoint',
    entrypoint,
    '--router-pattern',
    '**/*.router.ts',
    '--output',
    outDir,
    ...extra,
  ],
  { stdio: 'inherit' },
);
if (res.status !== 0) {
  rmSync(outDir, { recursive: true, force: true });
  process.exit(res.status ?? 1);
}

const generated = join(outDir, 'server.ts');
if (!existsSync(generated)) {
  console.error(`nestjs-trpc did not produce ${generated}`);
  process.exit(1);
}
const repoRoot = resolve(process.cwd(), '../..');
const target = resolve(repoRoot, 'packages/contracts/src', service, 'router.ts');
const banner = `/**\n * GENERATED by \`pnpm --filter ${service} contracts:generate\` (nestjs-trpc). Do not edit.\n */\n/* eslint-disable */\n`;
// Inside @bf/contracts the package must not import itself by name: rewrite to relative paths.
let body = readFileSync(generated, 'utf8')
  .replace(/from ["']@bf\/contracts\/([\w-]+)["']/g, (_m, sub) =>
    sub === service ? `from './schemas'` : `from '../${sub}'`,
  )
  .replace(/from ["']@bf\/contracts["']/g, `from '..'`);
// The CLI always imports zod; with contract-first schemas it is usually unused (noUnusedLocals).
if (!/\bz\./.test(body)) body = body.replace(/^import \{ z \} from ["']zod["'];\n/m, '');
writeFileSync(target, banner + body);
rmSync(outDir, { recursive: true, force: true });

const prettier = join(repoRoot, 'node_modules', 'prettier', 'bin', 'prettier.cjs');
if (existsSync(prettier))
  spawnSync(process.execPath, [prettier, '--write', '--log-level', 'warn', target], {
    stdio: 'inherit',
  });
console.log(`contracts: wrote ${target}`);
